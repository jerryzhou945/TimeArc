function langKey(lang) {
    return lang === "zh" || lang === "ja" ? lang : "en"
}

// Menu-bar wording. Unrecognized languages fall back to English, which is now
// simply the source text.
function menu(lang, source) {
    if (source === undefined || source === null)
        return source
    var l = langKey(lang)
    if (l === "zh")
        return menuZh[source] || zh[source] || source
    if (l === "ja")
        return menuJa[source] || ja[source] || source
    return source
}

function t(lang, source) {
    if (source === undefined || source === null)
        return source
    var key = source.toString()
    var l = langKey(lang)
    if (l === "zh")
        return zh[key] || key
    if (l === "ja")
        return ja[key] || key
    return key
}

// Templates are keyed by name, not by source text, so the composed result never
// has to round-trip back through a dictionary.
function sentence(lang, key, params) {
    var l = langKey(lang)
    var template = l === "zh" ? (sentencesZh[key] || sentencesEn[key])
                 : l === "ja" ? (sentencesJa[key] || sentencesEn[key])
                 : sentencesEn[key]
    if (!template)
        template = key
    if (!params)
        return template
    for (var p in params)
        template = template.split("{" + p + "}").join(params[p])
    return template
}

function tag(lang, source) {
    return t(lang, source)
}

function category(lang, source) {
    return t(lang, source)
}

function categoryList(lang, source) {
    if (source === undefined || source === null)
        return ""
    var text = source.toString().trim()
    if (text.length === 0)
        return ""
    var parts = text.split(/[、，,\/]+/)
    if (parts.length <= 1)
        return category(lang, text)
    var out = []
    for (var i = 0; i < parts.length; i++) {
        var p = parts[i].trim()
        if (p.length > 0)
            out.push(category(lang, p))
    }
    return out.join(langKey(lang) === "en" ? ", " : "、")
}

function appName(row, languageMode, appVisual) {
    if (appVisual && appVisual.modelDisplayNameForLanguage)
        return appVisual.modelDisplayNameForLanguage(row, languageMode)
    return row && row.displayName ? row.displayName : ""
}

// Weekday initials are deliberately not dictionary lookups. Each language uses
// its own convention (English initials, Chinese numerals, Japanese elemental
// names) and the axis they label is width-constrained, so a shared key would
// force one language's width on the others. Previously these were inline
// `isEnglish() ? en : zh` ternaries, which silently gave Japanese the Chinese
// labels.
var weekdayNarrowEn = ["Mon", "Tue", "Wed", "Thu", "Fri", "Sat", "Sun"]
var weekdayNarrowZh = ["一", "二", "三", "四", "五", "六", "日"]
var weekdayNarrowJa = ["月", "火", "水", "木", "金", "土", "日"]

function weekdaysNarrow(lang) {
    var l = langKey(lang)
    return l === "zh" ? weekdayNarrowZh : l === "ja" ? weekdayNarrowJa : weekdayNarrowEn
}

// Heatmap axis: only alternate days are labelled, so the row stays readable.
function weekdaysHeat(lang) {
    var w = weekdaysNarrow(lang)
    return [w[0], "", w[2], "", w[4], "", ""]
}

// Dates are built per language instead of being assembled from translated
// fragments. "8月25日" and "Aug 25" order month and day differently and glue
// them with different separators, so no single template covers both; the old
// code hand-rolled this ternary at eight call sites and each one had to be
// kept in step by hand.
var monthShortEn = ["Jan", "Feb", "Mar", "Apr", "May", "Jun",
                    "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"]

// Indexed by Date.getDay(): Sunday first.
var weekdayAbbrEn = ["Sun", "Mon", "Tue", "Wed", "Thu", "Fri", "Sat"]
var weekdayAbbrZh = ["周日", "周一", "周二", "周三", "周四", "周五", "周六"]
var weekdayAbbrJa = ["日", "月", "火", "水", "木", "金", "土"]

function weekdaysAbbr(lang) {
    var l = langKey(lang)
    return l === "zh" ? weekdayAbbrZh : l === "ja" ? weekdayAbbrJa : weekdayAbbrEn
}

function monthShort(lang, monthIndex) {
    var m = Math.max(0, Math.min(11, monthIndex))
    var l = langKey(lang)
    return l === "en" ? monthShortEn[m] : (m + 1) + "月"
}

// month is 1-based, matching the calendar keys these call sites parse.
function monthDayNum(lang, month, day) {
    var l = langKey(lang)
    if (l === "en")
        return monthShortEn[Math.max(0, Math.min(11, month - 1))] + " " + day
    return month + "月" + day + "日"
}

function monthDay(lang, date) {
    return monthDayNum(lang, date.getMonth() + 1, date.getDate())
}

function yearMonth(lang, date) {
    var l = langKey(lang)
    if (l === "en")
        return monthShortEn[date.getMonth()] + " " + date.getFullYear()
    return date.getFullYear() + "年 " + (date.getMonth() + 1) + "月"
}

// Returns a Qt.formatDateTime pattern rather than a finished string: the
// caller owns the Date, and QML JS libraries have no locale of their own.
function monthDayTimeFormat(lang, hour12) {
    var clock = hour12 ? "h:mm AP" : "HH:mm"
    return langKey(lang) === "en" ? "MMM d  " + clock : "M月d日  " + clock
}

// Card text arrives from C++ as a template name plus its fields. The category
// and period words inside those fields are themselves source strings, so they
// are translated before substitution — otherwise a Chinese sentence would come
// out with an English category dropped into the middle of it.
function fromModel(lang, key, params) {
    if (!key)
        return ""
    var resolved = {}
    for (var k in params) {
        var v = params[k]
        if (k === "category" || k === "period" || k === "mood")
            resolved[k] = categoryList(lang, v)
        else if (k === "month")
            resolved[k] = monthShort(lang, v - 1)   // service sends 1-based
        else
            resolved[k] = v
    }
    return sentence(lang, key, resolved)
}

// Date ranges and month labels arrive from the service as numbers (see
// mobile_usage_service.cpp), so the reader's language decides order and
// separators rather than the service's.
function dateRange(lang, parts) {
    if (!parts)
        return ""
    return sentence(lang, "dateRange", {
        from: monthDayNum(lang, parts.fromMonth, parts.fromDay),
        to: monthDayNum(lang, parts.toMonth, parts.toDay)
    })
}

function yearMonthLabel(lang, parts) {
    if (!parts)
        return ""
    return yearMonth(lang, new Date(parts.year, parts.month - 1, 1))
}

// Month name alone, for titles that name a month rather than a date.
function monthLabel(lang, parts) {
    return parts ? monthShort(lang, parts.month - 1) : ""
}

// Report/dashboard fields carry either a structured form (from the service) or
// a finished string (from the --mobile-preview fixtures). Prefer the structured
// form; fall back so preview mode keeps rendering.
function reportMonthLabel(lang, report) {
    if (!report)
        return ""
    return report.monthLabelParts ? yearMonthLabel(lang, report.monthLabelParts)
                                  : (report.monthLabel || "")
}

function reportTitle(lang, report) {
    if (!report)
        return ""
    return report.titleKey ? fromModel(lang, report.titleKey, report.titleParams)
                           : (report.title || "")
}

function reportRange(lang, model) {
    if (!model)
        return ""
    return model.rangeDates ? dateRange(lang, model.rangeDates)
                            : (model.rangeText || "")
}

// Trend bars and the aggregate fact come from StatsViewModel.js, which is kept
// free of I18n so the Node regression tests can run it. It emits a label key
// plus an index; the rendering happens here.
function trendLabel(lang, bar) {
    if (!bar)
        return ""
    if (bar.label)
        return t(lang, bar.label)
    if (bar.labelKey === "weekOfMonth")
        return sentence(lang, "weekOfMonth", {n: bar.labelIndex + 1})
    if (bar.labelKey === "monthOfYear")
        return monthShort(lang, bar.labelIndex)
    if (bar.labelKey === "weekdayNarrow")
        return weekdaysNarrow(lang)[bar.labelIndex] || String(bar.labelIndex + 1)
    return ""
}

function aggregateFact(lang, fact) {
    if (!fact || !fact.key)
        return ""
    var p = fact.params || {}
    return sentence(lang, fact.key, {
        category: category(lang, p.category),
        range: t(lang, p.range),
        peak: trendLabel(lang, {label: p.peakLabel,
                                labelKey: p.peakLabelKey,
                                labelIndex: p.peakLabelIndex})
    })
}

// Enumeration separator differs by script: English lists with ", ", Chinese and
// Japanese with the full-width "、".
function appsText(lang, apps) {
    if (!apps || apps.length === 0)
        return ""
    return apps.join(langKey(lang) === "en" ? ", " : "、")
}
