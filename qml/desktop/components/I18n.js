// 认不出的语言退回英文（与 menu() 一致）：中文当兜底时会变成吸引子——任何空值/
// 脏值都把界面拉回中文，en/ja 的会话反而莫名其妙冒出中文。显式的 zh/ja 不受影响。
function langKey(lang) {
    return lang === "zh" || lang === "ja" ? lang : "en"
}

// 菜单栏取词。只有明确的 zh/ja 走各自的表，其余一律英文——包括意外值：
// 认不出的语言退回英文可以接受，退回中文会让 en/ja 的菜单突然冒出中文。
function menu(lang, source) {
    if (lang === "zh")
        return source
    if (lang === "ja")
        return menuJa[source] || menuEn[source] || source
    return menuEn[source] || source
}

function t(lang, source) {
    if (source === undefined || source === null)
        return source
    var key = source.toString()
    var l = langKey(lang)
    if (l === "en" && en[key])
        return en[key]
    if (l === "ja")
        return ja[key] || en[key] || key
    return key
}

function sentence(lang, key, params, fallback) {
    var l = langKey(lang)
    var template = l === "en" ? sentencesEn[key] : (l === "ja" ? (sentencesJa[key] || sentencesEn[key]) : fallback)
    if (!template)
        template = fallback || key
    if (!params)
        return template
    for (var p in params)
        template = template.split("{" + p + "}").join(params[p])
    return template
}

function tag(lang, source) {
    return t(lang, source)
}

function category(lang, source) {
    return t(lang, source)
}

function categoryList(lang, source) {
    if (source === undefined || source === null)
        return ""
    var text = source.toString().trim()
    if (text.length === 0)
        return ""
    var parts = text.split(/[、，,\/]+/)
    if (parts.length <= 1)
        return category(lang, text)
    var out = []
    for (var i = 0; i < parts.length; i++) {
        var p = parts[i].trim()
        if (p.length > 0)
            out.push(category(lang, p))
    }
    return out.join(langKey(lang) === "en" ? ", " : "、")
}

function duration(lang, source) {
    if (source === undefined || source === null)
        return ""
    var text = source.toString()
    if (langKey(lang) === "en")
        return text.replace(/^约\s*/, "about ").replace(/^about\s*/, "about ")
    return t(lang, text)
}

function smartText(lang, source) {
    if (source === undefined || source === null)
        return source
    var text = source.toString()
    if (text.length === 0)
        return ""
    var direct = t(lang, text)
    if (direct !== text)
        return direct
    if (langKey(lang) !== "en")
        return text

    var m = text.match(/^(.+):\s*(.+)使用$/)
    if (m)
        return m[1] + ": " + category(lang, m[2]) + " use"

    m = text.match(/^(.+)使用$/)
    if (m) {
        var translatedUsePrefix = t(lang, m[1])
        return translatedUsePrefix !== m[1] ? translatedUsePrefix + " Use" : category(lang, m[1]) + " Use"
    }

    m = text.match(/^(.+)\s*本月使用约\s*([^，]+)，多集中在(.+)，最长连续\s*([^。]+)。$/)
    if (m)
        return sentence(lang, "monthlyAppAnalysis", {
            app: t(lang, m[1].trim()),
            time: m[2],
            period: category(lang, m[3]),
            longest: duration(lang, m[4])
        }, text)

    m = text.match(/^(.+)\s*本月使用\s*(约\s*|about\s*)?([^，]+)，主要在(.+)，单次最长\s*([^，]+)，共打开\s*(\d+)\s*次。$/)
    if (m)
        return sentence(lang, "monthlyAppAnalysisWithLaunches", {
            app: t(lang, m[1].trim()),
            time: duration(lang, (m[2] ? m[2] : "") + m[3]),
            period: t(lang, m[4]),
            longest: duration(lang, m[5]),
            launches: m[6]
        }, text)

    m = text.match(/^(.+)\s*今天使用约\s*([^，]+)，多集中在(.+)，最长连续\s*([^。]+)。$/)
    if (m)
        return sentence(lang, "todayAppAnalysis", {
            app: t(lang, m[1].trim()),
            time: m[2],
            period: category(lang, m[3]),
            longest: duration(lang, m[4])
        }, text)

    m = text.match(/^(.+)\s*今天使用\s*(约\s*|about\s*)?([^，]+)，主要在(.+)，单次最长\s*([^，]+)，共打开\s*(\d+)\s*次。$/)
    if (m)
        return sentence(lang, "todayAppAnalysisWithLaunches", {
            app: t(lang, m[1].trim()),
            time: duration(lang, (m[2] ? m[2] : "") + m[3]),
            period: t(lang, m[4]),
            longest: duration(lang, m[5]),
            launches: m[6]
        }, text)

    m = text.match(/^今天有\s*(\d+)\s*段连续使用，最长\s*([^，]+)，主要在(.+)。$/)
    if (m)
        return sentence(lang, "continuousSessions", {
            count: m[1],
            longest: duration(lang, m[2]),
            category: categoryList(lang, m[3])
        }, text)

    m = text.match(/^(本周|本月|本年)你主要把时间花在「(.+)」（(\d+%)），共计\s*(.+)。$/)
    if (m)
        return sentence(lang, "insightMain", {
            range: t(lang, m[1]),
            app: category(lang, m[2]),
            percent: m[3],
            time: m[4]
        }, text)

    m = text.match(/^(\d+)\s*次$/)
    if (m)
        return sentence(lang, "timesCount", {count: m[1]}, text)

    return text.replace(/约\s*/g, "about ")
}

function appName(row, languageMode, appVisual) {
    if (appVisual && appVisual.modelDisplayNameForLanguage)
        return appVisual.modelDisplayNameForLanguage(row, languageMode)
    return row && row.displayName ? row.displayName : ""
}
